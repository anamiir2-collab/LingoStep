/* ============================================================
   Content engine — gen-all.js
   Runs all eight section generators in ONE process so the
   global sentence-dedup registry sees every section, then
   writes data/lesson-manifest.js and a content report.
   Usage: node scripts/content/gen-all.js
   ============================================================ */

import { writeFileSync, readdirSync, statSync, rmSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { resetRegistry, registrySize } from './lib/builder.js';
import { normalizeForDup } from '../../js/lesson-schema.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');

async function main() {
  resetRegistry();

  // clean lesson output (regenerated fully each time)
  const lessonsDir = join(ROOT, 'lessons');
  for (const dir of readdirSync(lessonsDir)) {
    const p = join(lessonsDir, dir);
    if (statSync(p).isDirectory()) rmSync(p, { recursive: true, force: true });
  }

  const mods = [
    ['basics', await import('./gen-basics.js')],
    ['tenses-a', await import('./gen-tenses-a.js')],
    ['tenses-b', await import('./gen-tenses-b.js')],
    ['grammar', await import('./gen-grammar.js')],
    ['conversations', await import('./gen-conversations.js')],
    ['practical-scenarios', await import('./gen-practical.js')],
    ['vocabulary', await import('./gen-vocabulary.js')],
    ['listening-writing', await import('./gen-listening.js')],
    ['capstone', await import('./gen-capstone.js')],
  ];

  const perSection = [];
  const titles = [];
  for (const [label, mod] of mods) {
    const r = mod.buildAll();
    perSection.push({ label, ...r });
    console.log(`  ${label}: ${r.lessons} lessons, ${r.exercises} exercises`);
  }

  // scan lesson files for the manifest
  const manifest = [];
  const seenIds = new Set();
  const SECTION_DIRS = ['basics', 'tenses', 'grammar', 'conversations', 'practical-scenarios', 'vocabulary', 'listening-writing'];
  for (const section of SECTION_DIRS) {
    const files = readdirSync(join(lessonsDir, section)).filter((f) => f.endsWith('.js')).sort();
    for (const file of files) {
      const url = new URL(`file://${join(lessonsDir, section, file)}`);
      const mod = await import(url.href);
      const l = mod.default;
      if (!l || !l.id || seenIds.has(l.id)) throw new Error(`duplicate/missing lesson id in ${file}`);
      seenIds.add(l.id);
      manifest.push({
        id: l.id,
        title: l.title,
        titleAr: l.titleAr,
        section,
        level: l.level,
        path: `lessons/${section}/${file}`,
        exercises: l.exercises.length,
        available: true,
      });
      titles.push(l.title);
    }
  }
  manifest.sort((a, b) => a.id.localeCompare(b.id));

  // verify sentence uniqueness: a sentence may repeat within one lesson
  // across different exercise types (dictation + gap-fill + scramble), but
  // never across lessons, and never twice as listen-and-type in one lesson
  const globalSeen = new Map(); // key -> lessonId
  let raw = 0;
  let dupes = 0;
  for (const entry of manifest) {
    const mod = await import(new URL(`file://${join(ROOT, entry.path)}`));
    const localLt = new Set();
    const localAny = new Set();
    for (const ex of mod.default.exercises) {
      const sentences = [];
      if (ex.type === 'listen-and-type') sentences.push(ex.en);
      if (ex.type === 'word-order') sentences.push(ex.en);
      if (ex.type === 'fill-blank') sentences.push(ex.en);
      for (const s of sentences) {
        raw += 1;
        const key = normalizeForDup(s);
        if (ex.type === 'listen-and-type') {
          if (localLt.has(key)) { dupes += 1; console.error(`  INTRA-LT DUP [${entry.id}]: ${s}`); }
          localLt.add(key);
        }
        if (globalSeen.has(key) && globalSeen.get(key) !== entry.id && !localAny.has(key)) {
          // cross-lesson repeat of a sentence not already used in this lesson
          dupes += 1;
          console.error(`  CROSS DUP [${entry.id}]: ${s}`);
        }
        localAny.add(key);
        if (!globalSeen.has(key)) globalSeen.set(key, entry.id);
      }
    }
  }

  const manifestSrc = `/* LingoStep lesson manifest — generated by scripts/content/gen-all.js
   120 lessons across 7 sections. Each entry maps to an independent
   lesson module loaded on demand by js/lesson-loader.js. */
export const lessonManifest = ${JSON.stringify(manifest, null, 2)};
`;
  writeFileSync(join(ROOT, 'data/lesson-manifest.js'), manifestSrc, 'utf-8');

  const report = {
    generatedAt: new Date().toISOString(),
    totalLessons: manifest.length,
    totalExercises: manifest.reduce((s, m) => s + m.exercises, 0),
    uniqueSentences: globalSeen.size,
    rawSentences: raw,
    duplicates: dupes,
    sections: SECTION_DIRS.map((s) => ({
      section: s,
      lessons: manifest.filter((m) => m.section === s).length,
      exercises: manifest.filter((m) => m.section === s).reduce((a, m) => a + m.exercises, 0),
    })),
  };
  writeFileSync(join(ROOT, 'scripts/content-report.json'), JSON.stringify(report, null, 2), 'utf-8');

  console.log('\n=== gen-all summary ===');
  console.log(`lessons: ${report.totalLessons}, exercises: ${report.totalExercises}`);
  console.log(`raw sentences: ${raw}, unique: ${globalSeen.size}, duplicates: ${dupes}`);
  for (const s of report.sections) console.log(`  ${s.section}: ${s.lessons} lessons / ${s.exercises} exercises`);
  if (dupes > 0 || manifest.length < 120 || globalSeen.size < 6000) process.exit(1);
}

main().catch((e) => { console.error('gen-all failed:', e.message); process.exit(1); });
